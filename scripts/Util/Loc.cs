    static string[] _phrases;
    static readonly Dictionary<string, string> Cache = new();
    static readonly Regex Units = new(@"(?<=\d) ?(км/ч|к/с|мс|Гц|м|с|т)(?![А-Яа-яЁё])");

    static bool Cyrillic(string s)
    {
        foreach (char c in s)
            if (c >= '\u0400' && c <= '\u04FF') return true;
        return false;
    }

    /// <summary>The text in the chosen language.</summary>
    public static string T(string text)
    {
        if (!English || string.IsNullOrEmpty(text) || !Cyrillic(text)) return text;
        if (Table.TryGetValue(text, out string whole)) return whole;
        if (Cache.TryGetValue(text, out string done)) return done;
        if (_phrases == null)
        {
            // Phrases inside longer texts, longest first; one- and two-letter entries only stand alone.
            var list = new List<string>();
            foreach (string key in Table.Keys)
                if (key.Length >= 3) list.Add(key);
            list.Sort((a, b) => b.Length.CompareTo(a.Length));
            _phrases = list.ToArray();
        }
        string result = text;
        foreach (string phrase in _phrases)
            if (result.Contains(phrase)) result = result.Replace(phrase, Table[phrase]);
        result = Units.Replace(result, m => " " + m.Groups[1].Value switch { "км/ч" => "km/h", "к/с" => "fps", "мс" => "ms", "Гц" => "Hz", "м" => "m", "с" => "s", _ => "t" });
        if (Cache.Count > 4000) Cache.Clear();
        Cache[text] = result;
        return result;
    }

    /// <summary>Starts translating every control as it appears on the screen.</summary>
    public static void Hook(SceneTree tree)
    {
        tree.NodeAdded += node =>
        {
            if (English && node is Control control) Callable.From(() => Apply(control)).CallDeferred();
        };
    }

    /// <summary>Translates what a control shows: its text, its hint, the items of a list.</summary>
    public static void Apply(Control control)
    {
        if (!GodotObject.IsInstanceValid(control)) return;
        if (control.TooltipText != "") control.TooltipText = T(control.TooltipText);
        switch (control)
        {
            case Label label: label.Text = T(label.Text); break;
            case OptionButton option:
                for (int i = 0; i < option.ItemCount; i++) option.SetItemText(i, T(option.GetItemText(i)));
                break;
            case Button button: button.Text = T(button.Text); break;
            case LineEdit edit: edit.PlaceholderText = T(edit.PlaceholderText); break;
            case ItemList list:
                for (int i = 0; i < list.ItemCount; i++) list.SetItemText(i, T(list.GetItemText(i)));
                break;
            case TabContainer tabs:
                for (int i = 0; i < tabs.GetTabCount(); i++) tabs.SetTabTitle(i, T(tabs.GetTabTitle(i)));
                break;
        }
    }
